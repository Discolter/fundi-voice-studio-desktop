import assert from 'node:assert/strict';
import {normalizeState,roleStageName,actorPublicFeed,debtRows,applyRoleReviews,reviewVersion,castText} from '../package/web/core.js';
import {buildTaskSnapshot,mergeRoleStages,applyRoleStages} from '../package/web/task-cloud-sync.js';
import {actorWorkloadRows} from '../package/web/actor-workload.js';
import {actorDeliveryRows} from '../package/web/actor-statistics.js';
import {outstandingCastMessage} from '../package/web/episode-debts.js';
import {actorCabinetSnapshot} from '../package/web/actor-cabinet.js';

const state=normalizeState({schema:1,actors:[{id:'a',name:'Актёр',actorAccess:true}],projects:[{id:'p',title:'Проект',episodes:[{id:'ep',number:'1',roles:[{id:'r',character:'Герой',actorId:'a',status:'pickup',lineCount:15}],tasks:[]}]}]});
const project=state.projects[0],episode=project.episodes[0],role=episode.roles[0];
assert.equal(role.status,'pickup','Persistence must retain a pickup rather than default to waiting');
assert.equal(roleStageName(role.status),'Дописать');
const feed=actorPublicFeed(state,'a');
assert.equal(feed.roles[0].status,'pickup','Actor publication must preserve the distinct status');
assert.equal(debtRows(state,{status:'pickup'}).length,1);
assert.equal(debtRows(state,{status:'retake'}).length,0);
assert.equal(actorWorkloadRows(state)[0].pending,1);
assert.equal(actorDeliveryRows(state)[0].waiting,1);
assert.equal(actorDeliveryRows(state)[0].retakes,0,'Missing lines must not count as a retake');
assert.match(outstandingCastMessage(state,project,episode),/✎ Дописать/);
assert.match(castText(state,project,episode.id),/✎/);
assert.equal(actorCabinetSnapshot(state.actors[0],feed,null).debts.length,1);

const original=buildTaskSnapshot(state),remote=structuredClone(original);
role.status='waiting';
const local=buildTaskSnapshot(state),base=structuredClone(local);
const merged=mergeRoleStages(local,base,remote);
assert.deepEqual(merged.conflicts,[]);
applyRoleStages(state,merged.stages);
assert.equal(role.status,'pickup','Web-to-desktop stage synchronization must retain pickups');
const review={actorId:'a',roleId:'r',state:'pickup',submissionId:7,messageId:8};
role.status='done';
applyRoleReviews(state,[review]);
assert.equal(role.status,'pickup','A new pickup decision must reopen accepted work');
role.status='processing';role.reviewSeen=reviewVersion(review);
applyRoleReviews(state,[review]);
assert.equal(role.status,'processing','Repeated reviews must respect a newer manual selection');
role.status='recording';role.reviewSeen='';
applyRoleReviews(state,[review]);
assert.equal(role.status,'recording','Starting a pickup must stay visibly in recording');
applyRoleReviews(state,[{...review,state:'pending',submissionId:9,messageId:9}]);
assert.equal(role.status,'received','Submitting the missing lines must return the role to review');
console.log('PASS: pickups persist, sync, reopen, stay separate from retakes and return to review');
