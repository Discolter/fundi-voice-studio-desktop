import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {episodeEngagedActorCount,episodeRoleActorOptions,seedState} from '../package/web/core.js';

const state=seedState();
state.actors=[{id:'a',name:'Один'},{id:'b',name:'Два'},{id:'c',name:'Три'}];
const ep={roles:[]};
const count=()=>episodeEngagedActorCount(state,ep.roles);
assert.equal(count(),0,'empty episode');
ep.roles.push({id:'r1',character:'Главный',actorId:'a',actor:'Один'});
assert.equal(count(),1,'one assigned actor');
ep.roles.push({id:'r2',character:'Второстепенный',actorId:'a',actor:'Один'});
assert.equal(count(),1,'one actor in several roles is counted once');
ep.roles.push({id:'r3',character:'Массовка',actorId:'b',actor:'Два'});
assert.equal(count(),2,'different actors are counted separately');
ep.roles.push({id:'r4',character:'Не назначен',actorId:'',actor:''});
assert.equal(count(),2,'unassigned roles are not counted');
ep.roles.push({id:'r5',character:'Голос за кадром',actorId:'',actor:'Старый исполнитель'});
assert.equal(count(),3,'historical text-only casting counts once');
ep.roles.push({id:'r6',character:'Другой персонаж',actorId:'',actor:' старый исполнитель '});
assert.equal(count(),3,'legacy names are de-duplicated regardless of case/spacing');
ep.roles[1].actorId='c';
assert.equal(count(),4,'changing the assigned actor recalculates the result');
ep.roles[0].actorId='';ep.roles[0].actor='';
assert.equal(count(),3,'unassigning an actor recalculates the result');
assert.equal(episodeRoleActorOptions(state,ep.roles).filter(x=>x.key!=='unassigned').length,count());
const app=readFileSync(new URL('../package/web/app.js',import.meta.url),'utf8');
assert.ok(app.includes('const engagedActors=episodeEngagedActorCount(state,ep.roles)'),'count all roles, not current filtered rows');
assert.ok(app.includes('Ролей: ${ep.roles.length} · Актёров: ${engagedActors}'),'display alongside original role count');
assert.ok(app.includes('Ролей: 0 · Актёров: 0'),'empty episode shows both zeroes');
console.log('PASS: episode role and unique actor counters stay in sync across casting changes');
