import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const source=readFileSync('package/web/app.js','utf8');
const css=readFileSync('package/web/compact.css','utf8');
const a=source.indexOf('function studioVacationIdentity(');
const b=source.indexOf('function renderVacations(){',a);
assert.ok(a>=0&&b>a,'Vacations must have the shared identity renderer');
const identitySource=source.slice(a,b);
const actor={id:'actor-1',name:'Артас',telegram:'ArthassMenthil',avatar:'data:image/png;base64,STUB'};
const state={actors:[actor]};
const cleanTelegram=value=>String(value||'').replace(/^@+/,'').trim();
const e=value=>String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const avatar=actor=>'<span class="fake-avatar">'+e(actor.avatar||actor.name)+'</span>';
const identity=new Function('state','cleanTelegram','actorPickAvatar','e',identitySource+';return studioVacationIdentity;')(state,cleanTelegram,avatar,e);
const html=identity('actor-1','wrong_cloud_username');
assert.match(html,/Артас/,'Prefer the Studio actor display name');
assert.match(html,/@ArthassMenthil/,'Use Telegram from Studio, not the Cloud username');
assert.doesNotMatch(html,/wrong_cloud_username/,'Cloud login is not a Telegram handle');
assert.match(html,/data:image\/png/,'Render a saved Studio avatar');
const missing=identity('not-in-studio','@old_cloud_name');
assert.match(missing,/@old_cloud_name/,'A historical Cloud-only actor still has fallback identity');
assert.doesNotMatch(missing, /@@/,'Never show duplicate @ prefixes');
const changed=source.slice(source.indexOf('function renderVacations(){'),source.indexOf('function renderCloudConnection(){'));
assert.match(changed,/studioVacationIdentity\(v\.actorId,v\.username\)/,'Use actor identities in vacation cards, events and history');
assert.ok(changed.split('studioVacationIdentity(v.actorId,v.username)').length>=3,'Both current vacations and history/events use the same identity renderer');
assert.ok(css.includes('.studio-vacation-identity .actor-pick-avatar'),'Vacation card avatars need fixed sizes');
assert.ok(source.includes('filter(a=>!a.retiredAt&&!vacationFor(a.id))'),'Do not offer removed actors new vacations');
console.log('PASS: vacation identities use Studio avatars and Telegram handles with Cloud fallback');
